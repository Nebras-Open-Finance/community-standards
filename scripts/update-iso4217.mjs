/**
 * Regenerates src/data/iso4217.ts from the ISO 4217 List One (current codes)
 * published by SIX, the ISO 4217 maintenance agency.
 *
 * Every code is kept and given a category, so consumers decide what to accept:
 *   currency        — a circulating national or regional currency
 *   fund            — a fund code (IsFund="true" in the source, e.g. CLF, USN)
 *   precious-metal  — XAU, XAG, XPD, XPT
 *   unit-of-account — bond-market units and supranational units (XBA–XBD, XDR, XUA, XSU)
 *   test            — XTS, reserved for testing
 *   no-currency     — XXX, for transactions where no currency is involved
 *
 * The X-code categories are listed explicitly below. A new non-fund X-code that
 * is not a known currency fails the run, so a human classifies it rather than
 * it silently becoming accepted as a currency.
 *
 * Not part of the build: ISO 4217 changes a few times a year at most. Run it,
 * review the diff, commit.
 *
 * Usage:  npm run update:iso4217 [-- --source <url-or-path>]
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')
const OUT_PATH = resolve(ROOT, 'src', 'data', 'iso4217.ts')

const DEFAULT_SOURCE =
  'https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml'

const PRECIOUS_METAL = new Set(['XAU', 'XAG', 'XPD', 'XPT'])
const UNIT_OF_ACCOUNT = new Set(['XBA', 'XBB', 'XBC', 'XBD', 'XDR', 'XUA', 'XSU'])
const TEST = new Set(['XTS'])
const NO_CURRENCY = new Set(['XXX'])
// Regional currencies whose code happens to start with X.
const X_CURRENCY = new Set(['XAF', 'XCD', 'XCG', 'XOF', 'XPF'])

function arg(name) {
  const i = process.argv.indexOf(name)
  return i > -1 ? process.argv[i + 1] : undefined
}

async function load(source) {
  if (!/^https?:/.test(source)) return readFileSync(source, 'utf-8')
  const res = await fetch(source)
  if (!res.ok) throw new Error(`GET ${source} → ${res.status}`)
  return res.text()
}

const decode = (s) => s
  .replace(/&quot;/g, '"').replace(/&apos;/g, "'")
  .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&')
  .trim()

function categorise(code, isFund) {
  if (isFund) return 'fund'
  if (PRECIOUS_METAL.has(code)) return 'precious-metal'
  if (UNIT_OF_ACCOUNT.has(code)) return 'unit-of-account'
  if (TEST.has(code)) return 'test'
  if (NO_CURRENCY.has(code)) return 'no-currency'
  if (code.startsWith('X') && !X_CURRENCY.has(code)) {
    throw new Error(`Unclassified X-code ${code}: add it to a category in scripts/update-iso4217.mjs`)
  }
  return 'currency'
}

async function main() {
  const source = arg('--source') ?? DEFAULT_SOURCE
  const xml = await load(source)

  const published = xml.match(/<ISO_4217[^>]*\bPblshd="([^"]+)"/)?.[1]
  if (!published) throw new Error('No Pblshd date on <ISO_4217>; is this List One?')

  const byCode = new Map()
  for (const [, entry] of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
    const code = entry.match(/<Ccy>([^<]*)<\/Ccy>/)?.[1]?.trim()
    if (!code) continue // e.g. ANTARCTICA: a country with no universal currency
    if (!/^[A-Z]{3}$/.test(code)) throw new Error(`Malformed code ${JSON.stringify(code)}`)
    const nm = entry.match(/<CcyNm([^>]*)>([^<]*)<\/CcyNm>/)
    const name = decode(nm?.[2] ?? '')
    const category = categorise(code, /IsFund="true"/.test(nm?.[1] ?? ''))
    const seen = byCode.get(code)
    if (seen && (seen.name !== name || seen.category !== category)) {
      throw new Error(`${code} appears as both ${seen.name}/${seen.category} and ${name}/${category}`)
    }
    byCode.set(code, { code, name, category })
  }

  const rows = [...byCode.values()].sort((a, b) => a.code.localeCompare(b.code))
  if (rows.length < 150) throw new Error(`Only ${rows.length} codes parsed; refusing to write`)

  const width = Math.max(...rows.map((r) => r.category.length)) + 3
  const lines = rows.map((r) =>
    `  { code: '${r.code}', category: ${`'${r.category}',`.padEnd(width)} name: ${JSON.stringify(r.name)} },`)

  const out = `// GENERATED by scripts/update-iso4217.mjs — do not edit by hand.
// Source: ISO 4217 List One (current codes), SIX, published ${published}.
// ${DEFAULT_SOURCE}
//
// Every current code is listed. \`category\` marks the ones that are not
// circulating currencies, so a consumer can decide which to accept.

export type Iso4217Category =
  | 'currency'
  | 'fund'
  | 'precious-metal'
  | 'unit-of-account'
  | 'test'
  | 'no-currency'

export interface Iso4217Code {
  code: string
  category: Iso4217Category
  name: string
}

export const ISO_4217_PUBLISHED = '${published}'

export const ISO_4217: readonly Iso4217Code[] = [
${lines.join('\n')}
]
`
  writeFileSync(OUT_PATH, out)
  const counts = {}
  for (const r of rows) counts[r.category] = (counts[r.category] ?? 0) + 1
  console.log(`Wrote ${rows.length} codes (published ${published}) to src/data/iso4217.ts`, counts)
}

main().catch((err) => {
  console.error(err.message)
  process.exit(1)
})
